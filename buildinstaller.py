"""Build ClearBudgetSetup.exe (single-file per-user installer).

Workflow:

1) Build app bundle:     python buildexe.py
2) Build payload+setup:  python buildinstaller.py

The setup program is a PySide6 application of its own, so it carries a second
copy of Qt. A single-file build has no folder to prune afterwards, so this
script writes a PyInstaller spec that filters the collected binaries and data
through `build_prune.should_prune` before they are packed; the rules are the
same ones `buildexe.py` applies to the application folder.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

import shrink_artwork
import stamp_version
from installer.constants import APP_ICON_PNG_NAMES

PROJECT_ROOT = Path(__file__).resolve().parent

# The spec PyInstaller runs. Generated into the work directory on every build
# and never tracked (`*.spec` is gitignored): this string is its one source.
# `datas` and `icon` are filled in as Python literals, so paths with spaces or
# backslashes survive. The filters are the whole reason for the spec: nothing
# on the command line can drop a binary a hook decided to collect.
_SPEC_TEMPLATE = """\
# Generated by buildinstaller.py. Edit that script, not this file.
import sys

sys.path.insert(0, {root!r})

from build_prune import EXCLUDED_MODULES, should_prune

a = Analysis(
    [{entry!r}],
    pathex=[{root!r}],
    datas={datas!r},
    hiddenimports=["installer.ui.worker"],
    excludes=list(EXCLUDED_MODULES),
)
a.binaries = [item for item in a.binaries if not should_prune(item[0])]
a.datas = [item for item in a.datas if not should_prune(item[0])]
pyz = PYZ(a.pure)
exe = EXE(
    pyz,
    a.scripts,
    a.binaries,
    a.datas,
    [],
    name="ClearBudgetSetup",
    console=False,
    icon={icon!r},
    upx=False,
)
"""


def _require_windows() -> None:
    if os.name != "nt":
        raise SystemExit("buildinstaller.py is Windows-only")


def _run(cmd: list[str]) -> None:
    print("\n> " + " ".join(cmd))
    subprocess.check_call(cmd)


def _retry_unlink(path: Path, *, attempts: int = 20, delay_s: float = 0.15) -> None:
    """Try to delete a file that may be briefly locked by AV/Explorer."""

    if not path.exists():
        return

    last_exc: Exception | None = None
    for _ in range(attempts):
        try:
            path.unlink(missing_ok=True)
            return
        except Exception as exc:  # noqa: BLE001
            last_exc = exc
            time.sleep(delay_s)
    if last_exc:
        raise last_exc


def _replace_file(src: Path, dst: Path) -> None:
    """Replace dst with src.

    On Windows, the destination may be locked if the exe is running.
    """

    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.exists():
        _retry_unlink(dst)
    shutil.move(str(src), str(dst))


def main() -> int:
    _require_windows()

    # Propagate the canonical VERSION into static docs before packaging.
    stamp_version.main()

    # 1) Build payload zip + manifest.
    _run([sys.executable, "-m", "installer.build_payload"])

    # 2) Build installer exe.
    final_dist_root = PROJECT_ROOT / "dist-installer"
    work_root = PROJECT_ROOT / "build" / "installer"

    # Build into a temporary dist folder and then move into place. This avoids
    # PyInstaller failing mid-build if an old ClearBudgetSetup.exe is still locked.
    temp_dist_root = PROJECT_ROOT / "dist-installer.build"

    for p in [temp_dist_root, work_root]:
        if p.exists():
            shutil.rmtree(p, ignore_errors=True)

    entrypoint = PROJECT_ROOT / "installer" / "app.py"
    icon = PROJECT_ROOT / "ClearBudget.ico"

    payload_zip = PROJECT_ROOT / "installer" / "payload" / "payload.zip"
    manifest_json = PROJECT_ROOT / "installer" / "payload" / "manifest.json"

    if not payload_zip.exists() or not manifest_json.exists():
        raise SystemExit("Payload build did not produce payload.zip/manifest.json")

    # The theme toggle's two faces ship at the size they are drawn at, the
    # same copies the application carries.
    artwork = shrink_artwork.shrink(work_root / "artwork")
    by_name = {path.name: path for path in artwork}

    # Include the icon file so the runtime can set the window/taskbar icon.
    # NOTE: This is separate from the EXE icon, which only sets the embedded
    # exe icon.
    add_data = [
        (str(payload_zip), "installer/payload"),
        (str(manifest_json), "installer/payload"),
        # Version file (read by clear_budget.version module).
        (str(PROJECT_ROOT / "VERSION"), "."),
        # Licences (shown in installer UI and shipped for runtime UI dialogs).
        (str(PROJECT_ROOT / "LICENSE"), "."),
        # Ship icon assets so the installer can set its own window icon and so
        # it can deploy them next to ClearBudget.exe (for taskbar + shortcut icon
        # consistency).
        (str(icon), "."),
        # The sized PNGs, by the names the setup program deploys, so the
        # staged list and the deployed list cannot drift apart.
        *((str(PROJECT_ROOT / name), ".") for name in APP_ICON_PNG_NAMES),
        # The theme toggle's two faces, the same artwork the application's
        # tray wears, so the setup program and the app never disagree about
        # which picture means which mode.
        (str(by_name["lightmode.png"]), "."),
        (str(by_name["darkmode.png"]), "."),
    ]

    # The embedded PE icon in the spec is what Explorer shows for
    # ClearBudgetSetup.exe. The staged ICO above is a separate concern: it is
    # the RUNTIME copy the setup program reads for its window and deploys
    # beside the installed app. Without the embedded one PyInstaller uses its
    # own default, a diskette.
    spec_path = work_root / "ClearBudgetSetup.spec"
    work_root.mkdir(parents=True, exist_ok=True)
    spec_path.write_text(
        _SPEC_TEMPLATE.format(
            root=str(PROJECT_ROOT),
            entry=str(entrypoint),
            datas=add_data,
            icon=str(icon),
        ),
        encoding="utf-8",
    )

    _run(
        [
            sys.executable,
            "-m",
            "PyInstaller",
            "--noconfirm",
            "--clean",
            "--distpath",
            str(temp_dist_root),
            "--workpath",
            str(work_root),
            str(spec_path),
        ]
    )

    built_exe = temp_dist_root / "ClearBudgetSetup.exe"
    final_exe = final_dist_root / "ClearBudgetSetup.exe"

    if built_exe.exists():
        try:
            _replace_file(built_exe, final_exe)
        except PermissionError as exc:
            raise SystemExit(
                "Unable to overwrite the installer EXE because it is in use.\n"
                "Close any running installer instances.\n"
                "Then try again."
            ) from exc

        # Clean up temp dist folder.
        shutil.rmtree(temp_dist_root, ignore_errors=True)

        print(f"\nBuilt: {final_exe}")
        return 0

    print("\nBuild finished; expected installer exe not found.")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
